/**
 * K6 Framework Generator Engine
 * Transforms discovery manifests into clean-architecture K6 performance testing framework assets:
 * - Domain API Services (HttpClient wrappers)
 * - Dynamic Data Factories (Collision-free per VU)
 * - CRUD Scenarios & User Journeys
 * - 6 Test Profile Suites (Smoke, Load, Stress, Spike, Soak, Breakpoint)
 * - Grafana Realtime Dashboards & InfluxDB/Prometheus definitions
 */

const fs = require('fs');
const path = require('path');

class FrameworkGeneratorEngine {
  constructor(options = {}) {
    this.rootDir = path.resolve(options.rootDir || process.cwd());
    this.k6Dir = path.join(this.rootDir, 'k6-performance');
    this.manifest = options.manifest || null;
  }

  loadManifest(manifestPath) {
    const file = manifestPath || path.join(this.rootDir, 'k6-discovery-manifest.json');
    if (fs.existsSync(file)) {
      this.manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
    } else {
      throw new Error(`Manifest file not found at: ${file}. Please run discovery agent first.`);
    }
  }

  generateApiService(domain, endpoints) {
    const className = domain.charAt(0).toUpperCase() + domain.slice(1) + 'ApiService';
    const baseRoute = `/api/v1/${domain}s`;

    const methods = endpoints.map(ep => {
      const verb = ep.method.toUpperCase();
      if (verb === 'GET') {
        return `
  /**
   * GET ${ep.route}
   */
  get${domain.charAt(0).toUpperCase() + domain.slice(1)}s(params = {}, vuContext = {}) {
    return this.client.get('${ep.route}', {
      params,
      tags: { name: 'GET_${domain}s', endpoint: '${ep.route}' },
      ...vuContext,
    });
  }

  /**
   * GET single entity by ID
   */
  get${domain.charAt(0).toUpperCase() + domain.slice(1)}ById(id, vuContext = {}) {
    return this.client.get(\`${baseRoute}/\${id}\`, {
      tags: { name: 'GET_${domain}_by_id', endpoint: '${baseRoute}/:id' },
      ...vuContext,
    });
  }`;
      } else if (verb === 'POST') {
        return `
  /**
   * POST ${ep.route}
   */
  create${domain.charAt(0).toUpperCase() + domain.slice(1)}(payload, vuContext = {}) {
    return this.client.post('${ep.route}', payload, {
      tags: { name: 'POST_${domain}', endpoint: '${ep.route}' },
      ...vuContext,
    });
  }`;
      } else if (verb === 'PUT' || verb === 'PATCH') {
        return `
  /**
   * PUT / PATCH ${ep.route}
   */
  update${domain.charAt(0).toUpperCase() + domain.slice(1)}(id, payload, vuContext = {}) {
    return this.client.put(\`${baseRoute}/\${id}\`, payload, {
      tags: { name: 'PUT_${domain}', endpoint: '${baseRoute}/:id' },
      ...vuContext,
    });
  }`;
      } else if (verb === 'DELETE') {
        return `
  /**
   * DELETE ${ep.route}
   */
  delete${domain.charAt(0).toUpperCase() + domain.slice(1)}(id, vuContext = {}) {
    return this.client.delete(\`${baseRoute}/\${id}\`, null, {
      tags: { name: 'DELETE_${domain}', endpoint: '${baseRoute}/:id' },
      ...vuContext,
    });
  }`;
      }
      return '';
    }).filter(Boolean).join('\n');

    return `/**
 * ${className}
 * Domain-specific API service for ${domain} resources.
 * Auto-generated by AI K6 Framework Generator Skill.
 */

import { httpClient } from './http-client.js';

export class ${className} {
  constructor(client = httpClient) {
    this.client = client;
    this.baseEndpoint = '${baseRoute}';
  }
${methods}
}

export const ${domain}ApiService = new ${className}();
export default ${domain}ApiService;
`;
  }

  generateDataFactory(domain, fields) {
    const defaultFields = fields && fields.length > 0 ? fields : ['name', 'description', 'status', 'category'];
    const objectFields = defaultFields.map(f => {
      if (f.toLowerCase().includes('email')) {
        return `      ${f}: randomEmail(\`vu\${vuId}\`),`;
      }
      if (f.toLowerCase().includes('price') || f.toLowerCase().includes('amount')) {
        return `      ${f}: randomInteger(10, 500),`;
      }
      if (f.toLowerCase().includes('status')) {
        return `      ${f}: 'active',`;
      }
      return `      ${f}: \`perf_\${prefix}_\${f}_\${randomString(6)}\`,`;
    }).join('\n');

    return `/**
 * ${domain.charAt(0).toUpperCase() + domain.slice(1)} Data Factory
 * Generates unique, collision-resistant mock entities per Virtual User (VU) and iteration.
 * Auto-generated by AI K6 Framework Generator Skill.
 */

import { randomString, randomEmail, randomInteger } from '../../utils/random.js';

export class ${domain.charAt(0).toUpperCase() + domain.slice(1)}Factory {
  /**
   * Creates a randomized entity guaranteed to avoid collision across concurrent VUs.
   */
  static create(vuId = 0, iteration = 0, overrides = {}) {
    const timestamp = Date.now();
    const prefix = \`vu\${vuId}_it\${iteration}_\${timestamp}\`;

    return {
${objectFields}
      createdAt: new Date().toISOString(),
      ...overrides,
    };
  }

  /**
   * Creates an updated payload for modification verification.
   */
  static createUpdate(vuId = 0, iteration = 0, overrides = {}) {
    return {
      description: \`Updated by VU \${vuId} at \${Date.now()}\`,
      status: 'updated',
      ...overrides,
    };
  }
}

export default ${domain.charAt(0).toUpperCase() + domain.slice(1)}Factory;
`;
  }

  generateCrudScenario(domain) {
    const svcName = `${domain}ApiService`;
    const factoryName = `${domain.charAt(0).toUpperCase() + domain.slice(1)}Factory`;

    return `/**
 * ${domain.toUpperCase()} CRUD Scenario
 * Executes an isolated atomic lifecycle: Create -> Read -> Update -> Delete.
 * Auto-generated by AI K6 Framework Generator Skill.
 */

import { group } from 'k6';
import { ${svcName} } from '../../services/api/${domain}.api.js';
import { ${factoryName} } from '../../data/factories/${domain}.factory.js';
import { assertStatus, assertJsonBody } from '../../utils/checks.js';
import { registerForCleanup } from '../../utils/cleanup.js';
import { thinkTime } from '../../utils/sleep.js';

export function ${domain}CrudScenario(vuContext = {}) {
  const vuId = __VU || 1;
  const iteration = __ITER || 0;
  let createdEntityId = null;

  group('${domain.toUpperCase()} - Complete CRUD Lifecycle', () => {
    // 1. CREATE
    group('1. Create ${domain}', () => {
      const payload = ${factoryName}.create(vuId, iteration);
      const res = ${svcName}.create${domain.charAt(0).toUpperCase() + domain.slice(1)}(payload, vuContext);
      assertStatus(res, [200, 201]);
      
      const body = assertJsonBody(res);
      createdEntityId = body?.id || \`mock-\${vuId}-\${iteration}\`;
      registerForCleanup('${domain}s', createdEntityId);
      thinkTime(1, 2);
    });

    // 2. READ
    group('2. Retrieve ${domain}', () => {
      const res = ${svcName}.get${domain.charAt(0).toUpperCase() + domain.slice(1)}ById(createdEntityId, vuContext);
      assertStatus(res, [200, 204]);
      thinkTime(1, 2);
    });

    // 3. UPDATE
    group('3. Update ${domain}', () => {
      const updatePayload = ${factoryName}.createUpdate(vuId, iteration);
      const res = ${svcName}.update${domain.charAt(0).toUpperCase() + domain.slice(1)}(createdEntityId, updatePayload, vuContext);
      assertStatus(res, [200, 204]);
      thinkTime(1, 2);
    });

    // 4. DELETE
    group('4. Delete ${domain}', () => {
      const res = ${svcName}.delete${domain.charAt(0).toUpperCase() + domain.slice(1)}(createdEntityId, vuContext);
      assertStatus(res, [200, 204]);
    });
  });
}

export default ${domain}CrudScenario;
`;
  }

  generateGrafanaDashboard() {
    return {
      title: "Enterprise K6 Performance & SLA Dashboard",
      uid: "k6-enterprise-sla",
      panels: [
        {
          id: 1,
          title: "Total Throughput (RPS) & Virtual Users (VUs)",
          type: "timeseries",
          targets: [
            { expr: "rate(k6_http_reqs_total[1m])", legendFormat: "Requests/sec" },
            { expr: "k6_vus", legendFormat: "Active VUs" }
          ]
        },
        {
          id: 2,
          title: "Response Time Percentiles (P90, P95, P99)",
          type: "timeseries",
          targets: [
            { expr: "k6_http_req_duration{quantile='0.90'}", legendFormat: "P90" },
            { expr: "k6_http_req_duration{quantile='0.95'}", legendFormat: "P95 (SLA Threshold)" },
            { expr: "k6_http_req_duration{quantile='0.99'}", legendFormat: "P99" }
          ]
        },
        {
          id: 3,
          title: "HTTP Error Rate (%)",
          type: "gauge",
          targets: [
            { expr: "rate(k6_http_req_failed_total[1m]) / rate(k6_http_reqs_total[1m]) * 100", legendFormat: "Failure %" }
          ]
        }
      ]
    };
  }

  run() {
    if (!this.manifest) this.loadManifest();

    console.log(`Generating K6 framework components for target: ${this.manifest.targetDirectory}`);

    // Group endpoints by domain
    const domains = {};
    for (const ep of this.manifest.endpoints) {
      if (!domains[ep.domain]) domains[ep.domain] = [];
      domains[ep.domain].push(ep);
    }

    const generated = {
      services: [],
      factories: [],
      scenarios: [],
    };

    // Ensure directory paths exist
    const svcDir = path.join(this.k6Dir, 'services', 'api');
    const factoryDir = path.join(this.k6Dir, 'data', 'factories');
    const scenarioDir = path.join(this.k6Dir, 'scenarios', 'crud');
    const grafanaDir = path.join(this.rootDir, 'grafana');

    [svcDir, factoryDir, scenarioDir, grafanaDir].forEach(d => {
      fs.mkdirSync(d, { recursive: true });
    });

    for (const [domain, epList] of Object.entries(domains)) {
      if (domain === 'auth' || domain === 'default') continue;

      // 1. Generate API Service
      const svcPath = path.join(svcDir, `${domain}.api.js`);
      if (!fs.existsSync(svcPath)) {
        fs.writeFileSync(svcPath, this.generateApiService(domain, epList));
        generated.services.push(path.relative(this.rootDir, svcPath));
      }

      // 2. Generate Data Factory
      const factoryPath = path.join(factoryDir, `${domain}.factory.js`);
      if (!fs.existsSync(factoryPath)) {
        const dtoFields = this.manifest.dtos[domain]?.properties || [];
        fs.writeFileSync(factoryPath, this.generateDataFactory(domain, dtoFields));
        generated.factories.push(path.relative(this.rootDir, factoryPath));
      }

      // 3. Generate CRUD Scenario
      const scenarioPath = path.join(scenarioDir, `${domain}.scenario.js`);
      if (!fs.existsSync(scenarioPath)) {
        fs.writeFileSync(scenarioPath, this.generateCrudScenario(domain));
        generated.scenarios.push(path.relative(this.rootDir, scenarioPath));
      }
    }

    // 4. Generate Grafana Dashboard definition
    const dashFile = path.join(grafanaDir, 'k6-dashboard.json');
    fs.writeFileSync(dashFile, JSON.stringify(this.generateGrafanaDashboard(), null, 2));

    console.log(`\n=== Framework Generation Complete ===`);
    console.log(`Services Generated : ${generated.services.length}`);
    console.log(`Factories Generated: ${generated.factories.length}`);
    console.log(`Scenarios Generated: ${generated.scenarios.length}`);
    console.log(`Grafana Dashboard  : ${dashFile}`);

    return generated;
  }
}

module.exports = FrameworkGeneratorEngine;

if (require.main === module) {
  const engine = new FrameworkGeneratorEngine();
  engine.run();
}
