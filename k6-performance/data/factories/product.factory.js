import {
  generateVUSafeIdentifier,
  getRandomElement,
  getRandomPrice,
  getRandomInt
} from '../../utils/random.js';

/**
 * Dynamic Product Factory
 * Generates unique product items for performance testing scenarios.
 */

const CATEGORIES = ['Electronics', 'Accessories', 'Services', 'Cloud Tier', 'Hardware'];

export function createProductData(overrides = {}) {
  const code = generateVUSafeIdentifier('prd');
  const vu = typeof __VU !== 'undefined' ? __VU : 0;
  const iter = typeof __ITER !== 'undefined' ? __ITER : 0;

  return Object.assign(
    {
      /* PLACEHOLDER: Replace field names with your backend Product DTO schema */
      sku: `SKU-${code.toUpperCase()}`,
      name: `Performance Product ${code}`,
      description: `Synthetic load testing item generated by VU ${vu} in iteration ${iter}`,
      category: getRandomElement(CATEGORIES),
      price: getRandomPrice(15, 1200),
      inventory: getRandomInt(10, 500),
      inStock: true,
      tags: ['benchmark', `vu-${vu}`, 'k6-generated'],
    },
    overrides
  );
}

export function createUpdatedProductData(originalData = {}, overrides = {}) {
  return Object.assign(
    {},
    originalData,
    {
      name: `${originalData.name || 'Product'} (Updated)`,
      price: getRandomPrice(20, 1500),
      inventory: getRandomInt(1, 100),
    },
    overrides
  );
}
